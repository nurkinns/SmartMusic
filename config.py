"""
Центральный файл конфигурации приложения SmartMusic.
Здесь хранятся порты, константы состояний и базовые настройки.

ВАЖНО: секреты (ключи, токены) НЕ хранятся в коде.
Они читаются из переменных окружения или файла .env.
"""

import os
from pathlib import Path

# Загружаем переменные из файла .env, если он есть
try:
    from dotenv import load_dotenv
    load_dotenv()
except ImportError:
    print("⚠️ [Config] Не установлен python-dotenv. Чтение .env отключено.")


ROOT_DIR: Path = Path(__file__).resolve().parent

# --- Кодировка вывода в консоль ---
# На русской Windows консоль по умолчанию cp1251 (cp866), и обычный print()
# с эмодзи падает с UnicodeEncodeError. Принудительно переключаем на UTF-8
# с заменой непечатаемых символов, чтобы программа не падала.
import sys as _sys

for _stream in ("stdout", "stderr"):
    _obj = getattr(_sys, _stream, None)
    if _obj is not None and hasattr(_obj, "reconfigure"):
        try:
            _obj.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass


# Настройки GSI Сервера
GSI_SERVER_HOST: str = "127.0.0.1"
GSI_SERVER_PORT: int = 4000

# Константы состояний игры (Вайб-Матрица)
STATE_CALM: str = "CALM"          # Спокойный фарм, лес, перебежки
STATE_COMBAT: str = "COMBAT"      # Резкая драка, падение HP
STATE_DEATH: str = "DEATH"        # Герой мертв (в таверне)
STATE_VICTORY: str = "VICTORY"    # Победа
STATE_DEFEAT: str = "DEFEAT"      # Поражение
STATE_IDLE: str = "IDLE"          # Вне матча / Главное меню

# Настройки защиты от спама (Гистерезис)
DEFAULT_COOLDOWN_SECONDS: int = 30

# --------------------------------------------------------------------------
# Когда включается боевой вайб (см. src/triggers/damage_window.py)
# --------------------------------------------------------------------------
#
# Формулировка задана пользователем дословно:
#   «Смотреть на урон по герою за последние 10 секунд... если он больше
#    чем 15% хп героя на данный момент, включать комбат режим.»
#
# Раньше считалось падение между двумя соседними пакетами, и проверка
# выглядела так: `damage_taken > max_health * 0.15 or damage_taken > 0`.
# Второе условие срабатывало от ЛЮБОГО урона - от одного удара на фарме,
# от автоатаки, от тика. Отсюда в логе 13 переходов CALM -> COMBAT за
# 7 минут пробы героев: программа металась между вайбами, а кулдаун
# каждый раз глушил смену, и музыка в бою оставалась прежней.
COMBAT_DAMAGE_WINDOW_SECONDS: float = 10.0
COMBAT_DAMAGE_THRESHOLD: float = 0.15

# Порог «герой на низком HP» - отдельная причина для COMBAT, к урону
# отношения не имеет: загнал в таверну на фарме, и это уже драка.
COMBAT_LOW_HEALTH_PERCENT: int = 50

# --------------------------------------------------------------------------
# Настройки воспроизведения (см. src/player/audio_player.py)
# --------------------------------------------------------------------------

# Как достаём звук для плеера. Раньше варианта не было: DJ Brain жал
# мультимедийную клавишу «следующий трек» и надеялся, что в браузере уже
# открыт подходящий плейлист.
#
#   "download" - аудио скачивается один раз через yt-dlp и играется
#                локально. Основной вариант: старт мгновенный, во время
#                драки интернет не нужен.
#   "direct"   - VLC получает ссылку на ролик и тянет сам. Ничего не
#                качает, но старт зависит от сети, а VLC не всегда умеет
#                разбирать YouTube-ссылки. Запасной вариант.
#
# Переключается в Настройках и записывается обратно в этот файл.
PLAYER_MODE_DOWNLOAD: str = "download"
PLAYER_MODE_DIRECT: str = "direct"
PLAYER_MODE: str = os.getenv("SMARTMUSIC_PLAYER_MODE", PLAYER_MODE_DOWNLOAD)

# Громкость, которую выставил пользователь ползунком, в процентах.
# Хранится отдельно от ночного множителя: иначе ночной лимитер и
# ползунок дрались бы друг с другом - поднял ползунок, а Night
# Governor тут же срезал бы обратно, и винтик не делал бы ничего.
DEFAULT_VOLUME_PERCENT: int = 70

# Плавная смена трека (кроссфейд).
#
# Зачем: раньше трек заканчивался, и следующий начинался с чистого
# листа. На дропе это звучало как обрыв - доля секунды тишины, потом
# резкий удар. Особенно заметно в бою, где музыка переключается
# чаще всего.
#
# Сколько именно: меньше двух - не слышно, больше пяти - уже не
# переход, а наложение двух треков, в котором не разобрать, где какой.
# Три секунды - это как раз «воспринимается как один трек с дропом».
CROSSFADE_ENABLED: bool = True
CROSSFADE_SECONDS: float = 3.0

# Модуль вывода звука в VLC.
#
# Это не украшение, а условие работы кроссфейда. Проверено на этой
# машине (VLC 3.0.6):
#
#   directsound - громкость СВОЯ у каждого плеера в процессе.
#                 Наложение двух голосов работает.
#   wasapi      - громкость ОБЩАЯ на весь процесс. Поставил одному -
#                 поедет и второму, наложение невозможно: рампа
#                 затирает саму себя.
#
# wasapi на Windows стоит по умолчанию, поэтому модуль указан явно.
# Ставить другой нельзя: с ним плавная смена не работает вовсе.
PLAYER_AUDIO_OUTPUT: str = "directsound"

# Настройки Night Governor (Ночной режим)
NIGHT_MODE_ENABLED: bool = True     # Включен ли ночной лимитер
NIGHT_START_HOUR: int = 23           # Час начала ночи (23:00)
NIGHT_END_HOUR: int = 7             # Час окончания ночи (07:00)
NIGHT_VOLUME_FACTOR: float = 0.6    # Множитель громкости ночью (60% от нормальной)

# Настройки YouTube / YouTube Music OAuth2
# Файл для сохранения авторизационных токенов (секрет!)
YOUTUBE_TOKENS_FILE: str = os.getenv("YOUTUBE_TOKEN_FILE", "token.json")

# Файл с OAuth-данными приложения из Google Cloud Console (секрет!)
GOOGLE_CLIENT_SECRETS_FILE: str = os.getenv(
    "GOOGLE_CLIENT_SECRETS_FILE", "client_secret.json"
)

# Scope (права доступа): управление YouTube аккаунтом и плейлистами
YOUTUBE_SCOPES: list[str] = [
    "https://www.googleapis.com/auth/youtube.readonly",
    "https://www.googleapis.com/auth/youtube.force-ssl"
]

# Google OAuth2 Endpoints (официальные эндпоинты авторизации Google)
GOOGLE_AUTH_URL: str = "https://accounts.google.com/o/oauth2/v2/auth"
GOOGLE_TOKEN_URL: str = "https://oauth2.googleapis.com/token"

# --------------------------------------------------------------------------
# Настройки ИИ (локальная модель через Ollama)
