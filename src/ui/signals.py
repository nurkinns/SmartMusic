from PyQt6.QtCore import QObject, pyqtSignal

class GSISignals(QObject):
    """
    Сигналы для передачи событий из FastAPI в UI.
    """
    # Сигнал передает: (state, action_text, is_night, volume_factor)
    state_changed = pyqtSignal(str, str, bool, float)
    # Что DJ Brain поставил: (title, reason)
    #
    # Отдельный сигнал, потому что state_changed приходит на КАЖДЫЙ пакет
    # от игры, а трек меняется редко. Если бы трек ехал в том же сигнале,
    # подпись перерисовывалась бы десятки раз в секунду впустую.
    # title - пустая строка, если не играет ничего.
    track_changed = pyqtSignal(str, str)

    # Чем кончилась попытка включить трек: (подпись, получилось, причина)
    #
    # Отдельный сигнал, потому что track_changed описывает НАМЕРЕНИЕ - что
    # DJ Brain поставил, - а этот описывает РЕАЛЬНОСТЬ - зазвучало или нет.
    # Между ними проходят секунды скачивания, и именно в этот зазор
    # play_list() уже отвечает True. Без этого сигнала плашка в окне
    # показывала трек, который так и не начал играть, и ошибка загрузки
    # не доходила ни до кого.
    #
    # Эмитится из потока команд плеера, то есть не из GUI-потока.
    # Qt сам разложит это в очередь GUI-потока - так же, как он делает
    # для state_changed, который приходит из потока uvicorn.
    playback_result = pyqtSignal(str, bool, str)

# Единый экземпляр сигналов для всего приложения
gsi_signals = GSISignals()