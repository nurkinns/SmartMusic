"""
Окно урона: сколько HP герой потерял за последние N секунд.

Задача пользователя сформулирована дословно:

    «Смотреть на урон по герою за последние 10 секунд, также, как и
    мгновенный повтор nvidia записывает экран за последние минуты: если
    он больше чем 15% хп героя на данный момент, включать комбат режим.»

Смысл подмены очевиден на примере. Раньше COMBAT включался от падения
между двумя соседними пакетами, а GSI шлёт их десять раз в секунду:
любой удар на фарме, одна автоатака, тик от стака - и вайб COMBAT. На
пробе героев это дало 13 переходов CALM -> COMBAT за 7 минут, каждый
из которых глушился кулдауном, то есть музыка в бою и не менялась
вовсе, только дёргалась плашка в окне.

Что здесь не так и почему так
-----------------------------

**Разница краёв не годится.** `hp_now - hp_then` покажет ноль, если
герой получил 20% и отхилился обратно - а это и есть драка. Поэтому
берём сумму падений между соседними отсчётами, а не разницу первого и
последнего. Лечение внутри окна урон не отменяет.

**Урон считается только в падение.** Прибавление HP - это лечение или
отхиливание, а не урон. Иначе пакет с подросшим HP вычитался бы из
суммы и маскировал настоящий урон.

**Знаменатель - текущий HP, а не максимальный.** Так написано у
пользователя: «15% хп героя на данный момент». Практическое следствие:
у раненого героя порог ниже, поэтому короткая стычка на 40% здоровья
уже считается боем. Это не опечатка и не «неправильно посчитано» -
так и заказано.

**Отсчёты времени - свои.** Время берётся из `time.monotonic()` на
стороне программы, а не из полей пакета: в подписке GSI у нас только
`provider`, `map`, `hero` и `player`, игрового времени там нет. Заодно
это честно - окно длится в нашем восприятии, и если игра подвисла на
пару секунд, окно честно постареет вместе с ней.

**Часы можно подменить.** Тестам не нужно ждать десять настоящих
секунд: достаточно передать свои часы, которые двигаются вручную.

Границы окна
------------

Окно - это `[now - window, now]`. Отсчёт, попавший в этот отрезок,
считается, а всё, что старше, забывается.

Тонкость: у каждого отсчёта внутри окна должен быть предшественник,
иначе не с чем сравнивать. Поэтому из буфера выбрасывается не всё
старше границы, а всё, кроме одного - того самого предшественника.
Без этого кусок урона в начале окна молча терялся бы: герой получил 40
HP на 9-й секунде, а на 11-й отсчёт с границы вылетел, сумма стала
меньше, и бой переставал считаться боем на ровно тех двух секундах,
когда он важен.
"""

import time
from collections import deque
from typing import Callable, Deque, Optional, Tuple


class DamageWindow:
    """
    Кольцевой буфер отсчётов HP и сумма падений между ними.

    Хранит пары `(время, hp)` и считает урон как сумму положительных
    разностей соседних отсчётов, попавших в окно. Лечится за O(1) на
    пакет: спереди вычищается старое, сзади добавляется новое.

    Экземпляр на весь срок жизни программы создаётся в `dota_gsi.py`.
    """

    def __init__(self, window_seconds: float = 10.0,
                 clock: Optional[Callable[[], float]] = None) -> None:
        self._window = float(window_seconds)
        # monotonic, а не time(): системные часы умеют прыгать назад при
        # переводе времени или смене часового пояса, и окно сдвинулось бы
        # в прошлое вместе со всей историей боя.
        self._clock = clock if clock is not None else time.monotonic
        self._samples: Deque[Tuple[float, float]] = deque()

    # ------------------------------------------------------------------ #
    #  Основное
    # ------------------------------------------------------------------ #

    def observe(self, hp: float) -> float:
        """
        Добавить отсчёт HP и вернуть суммарный урон за окно.

        Вызывается на каждый пакет GSI. Первая точка, которую видит
        класс, ничего не возвращает: сравнивать не с чем.
        """
        now = self._clock()
        self._samples.append((now, float(hp)))
        self._trim(now)
        return self.damage()

    def damage(self) -> float:
        """Урон за окно на данный момент, без добавления отсчёта."""
        now = self._clock()
        self._trim(now)
        return self._sum()

    def reset(self) -> None:
        """
        Забыть всю историю.

        Вызывается при выходе из матча и на возрождении героя. Если не
        вызывать, окно переживёт смерть: герой умер на 300 HP - в буфер
        попало падение до нуля - и десять секунд после возрождения
        программа считала бы боем то, что уже кончилось.
        """
        self._samples.clear()

    # ------------------------------------------------------------------ #
    #  Внутреннее
    # ------------------------------------------------------------------ #

    def _trim(self, now: float) -> None:
        """
        Выбросить отсчёты, вышедшие за окно, но сохранить одного
        предшественника для самого раннего оставшегося.
        """
        cutoff = now - self._window
        # Условие именно `len > 2 и второй старше границы`: пока в буфере
        # меньше трёх отсчётов, выбрасывать нечего - сносить всё равно
        # не с чем будет сравнивать.
        while len(self._samples) > 2 and self._samples[1][0] < cutoff:
            self._samples.popleft()

    def _sum(self) -> float:
        """Сумма падений между соседними отсчётами, лечение не считаем."""
        total = 0.0
        previous = None
        for _, hp in self._samples:
            if previous is not None:
                drop = previous - hp
                if drop > 0:
                    total += drop
            previous = hp
        return total

    def __len__(self) -> int:
        """Сколько отсчётов в буфере. Для тестов и отладки."""
        return len(self._samples)
